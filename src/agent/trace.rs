//! Журнал хода агента.
//!
//! При включённой отладке в ленту диалога уходят события [`Ev::Trace`]:
//! вызовы инструментов, результаты, подтверждения и ошибки. В обычном режиме
//! трассировка молчит, чтобы не захламлять ленту.
//!
//! Наружу: [`trace`].

use super::{Ev, ToolCtx};

/// Записать строку в ленту как событие трассировки, если отладка включена.
pub fn trace(ctx: &ToolCtx, text: impl Into<String>) -> Option<Ev> {
    if !ctx.debug {
        return None;
    }
    Some(Ev::Trace { text: text.into() })
}
